import assert from 'node:assert/strict';
import {cleanLayout,HUD_PARTS} from '../mania-web/src/hud-layout.js';
const defaults=cleanLayout();
assert.equal(Object.keys(defaults).length,8);
assert.equal(defaults.error.w,HUD_PARTS.error.w*1.5);
assert.equal(defaults.error.h,HUD_PARTS.error.h*1.5);
assert.equal(defaults.error.beamScale,1,'Older layouts retain the original marker size');
assert.equal(cleanLayout({error:{beamScale:2.3}}).error.beamScale,2.3);
assert.equal(cleanLayout({error:{beamScale:Infinity}}).error.beamScale,1);
assert.equal(cleanLayout({error:{beamScale:0}}).error.beamScale,.5);
assert.equal(cleanLayout({error:{beamScale:99}}).error.beamScale,4);
assert.equal(defaults.error.beamOpacity,1,'Older layouts keep existing opacity');
assert.equal(cleanLayout({error:{beamOpacity:.35}}).error.beamOpacity,.35);
assert.equal(cleanLayout({error:{beamOpacity:0}}).error.beamOpacity,0,'Fully transparent markers are allowed');
assert.equal(cleanLayout({error:{beamOpacity:Infinity}}).error.beamOpacity,1);
assert.equal(cleanLayout({error:{beamOpacity:-1}}).error.beamOpacity,0);
assert.equal(cleanLayout({error:{beamOpacity:2}}).error.beamOpacity,1);
assert.equal(cleanLayout({error:{opacity:0}}).error.opacity,0,'The plate can be hidden independently');
const beamEdit=cleanLayout({error:{beamScale:2.4,beamOpacity:.35}});
assert.deepEqual(cleanLayout(JSON.parse(JSON.stringify(beamEdit))),beamEdit);
const edited=cleanLayout({combo:{x:100,y:200,w:400,h:100,opacity:.5,text:'连击',color:'#88eeff',visible:false}});
assert.deepEqual(edited.combo,{x:100,y:200,w:400,h:100,opacity:.5,text:'连击',color:'#88eeff',visible:false});
assert.deepEqual(cleanLayout(JSON.parse(JSON.stringify(edited))),edited,'Saved settings round-trip');
const invalid=cleanLayout({combo:{x:5000,y:-5,w:Infinity,h:-100,opacity:9,color:'url(bad)',text:'x'.repeat(700)},unknown:{x:1}});
assert.ok(invalid.combo.x+invalid.combo.w<=1920);
assert.ok(invalid.combo.y>=0&&invalid.combo.h>=12);
assert.equal(invalid.combo.opacity,1);assert.equal(invalid.combo.color,'');
assert.equal(invalid.combo.text.length,500);assert.equal(invalid.unknown,undefined);
console.log('PASS: eight editable HUD parts, 1.5x meter, persistent settings and invalid-layout recovery');
