const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require('playwright');
const replayPath=process.argv[2];
assert.ok(replayPath,'Usage: node renderer/tools/test_error_bar_browser.cjs <replay.osr>');
const output=path.resolve('scratch/error-bar-regression');fs.mkdirSync(output,{recursive:true});
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.OM_TEST_CHROME,args:['--no-proxy-server']});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:900}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/src/main.js',async route=>{
   const source=fs.readFileSync(path.resolve('renderer/mania-web/src/main.js'),'utf8');
   await route.fulfill({contentType:'text/javascript',body:source+`
window.__meterProbe=ms=>errorBarState(hitTraces,ms,hitMatch.windows.meh,hudLayout.layout.error.beamScale);
window.__meterHits=()=>hitTraces.filter(t=>t.matched&&t.kind==='head').map(t=>({time:t.time,result:t.result}));
window.__meterDraw=ms=>{
 const calls=[],original=hudCtx.roundRect,move=hudCtx.moveTo,line=hudCtx.lineTo,rect=hudCtx.fillRect;window.__meterArrow=[];window.__meterLines=[];window.__meterBackground=[];
 hudCtx.moveTo=function(x,y){window.__meterArrow.push({x,y,alpha:this.globalAlpha});return move.call(this,x,y);};
 hudCtx.lineTo=function(x,y){window.__meterLines.push({x,y});return line.call(this,x,y);};
 hudCtx.fillRect=function(x,y,w,h){window.__meterBackground.push({x,y,w,h,colour:this.fillStyle,alpha:this.globalAlpha});return rect.call(this,x,y,w,h);};
 hudCtx.roundRect=function(x,y,w,h,r){calls.push({x,y,w,h,r,colour:this.fillStyle,alpha:this.globalAlpha});return original.call(this,x,y,w,h,r);};
 try{window.__mania.drawFrame(ms);}finally{hudCtx.roundRect=original;hudCtx.moveTo=move;hudCtx.lineTo=line;hudCtx.fillRect=rect;}
 return calls;
};`});
  });
  await page.goto('http://127.0.0.1:8773/');
  await page.waitForFunction(()=>window.__mania?.skinState().loadedKey);
  await page.locator('#sourceSkinSel').selectOption('owc (default)');
  await page.waitForFunction(()=>window.__mania.skinState().loadedKey==='owc (default)'&&!window.__mania.skinState().loading);
  await page.locator('#bidInput').fill('4565844');
  await page.locator('#fOsr').setInputFiles(replayPath);await page.locator('#btnLoad').click();
  await page.locator('#sourceScene').waitFor({state:'hidden',timeout:120000});
  const hits=await page.evaluate(()=>window.__meterHits());assert.ok(hits.length>100);
  const time=hits[150].time+10;
  const baseline=await page.evaluate(ms=>window.__meterDraw(ms),time);
  assert.ok(baseline.length>5);assert.ok(new Set(baseline.map(m=>m.colour)).size>=2,'Actual replay draws different judgement colours');
  assert.ok(baseline.every(m=>m.r===m.w/2&&m.alpha>0&&m.alpha<=.85),'Rounded markers have fading alpha');
  const averages=await page.evaluate(times=>times.map(t=>window.__meterProbe(t).average),hits.slice(30,180).map(h=>h.time+10));
  assert.ok(Math.max(...averages)-Math.min(...averages)>.02,'Actual replay moves the average triangle');
  const arrowPositions=await page.evaluate(times=>times.map(t=>{window.__meterDraw(t);return window.__meterArrow[0].x;}),[hits[30].time+10,hits[100].time+10,hits[170].time+10]);
  assert.ok(Math.max(...arrowPositions)-Math.min(...arrowPositions)>1,'The drawn triangle changes position');
  const smooth=await page.evaluate(t=>[t-1,t,t+1,t+90,t+180].map(ms=>{window.__meterDraw(ms);return window.__meterArrow[0].x;}),hits[150].time);
  assert.ok(Math.abs(smooth[2]-smooth[1])<.5,'A new hit moves gently instead of snapping');
  await page.mouse.move(720,898);await page.locator('#btnEditHud').click();
  await page.locator('#hudPart').selectOption('error');await page.locator('#hud-beam-control').waitFor({state:'visible'});
  await page.locator('#hud-beam-scale').evaluate(el=>{el.value='2.4';el.dispatchEvent(new Event('input',{bubbles:true}));});
  assert.equal(await page.locator('#hud-beam-value').textContent(),'2.4×');
  const resized=await page.evaluate(ms=>window.__meterDraw(ms),time);
  const arrow=await page.evaluate(()=>window.__meterArrow[0]);
  assert.ok(arrow.y<resized[0].y,'Average triangle remains above enlarged markers');
  assert.ok((await page.evaluate(()=>window.__meterLines)).every(p=>p.y<arrow.y),'The triangle tip points downward');
  assert.equal(resized.length,baseline.length);
  resized.forEach((m,i)=>{
   assert.ok(Math.abs(m.w/baseline[i].w-2.4)<1e-9);assert.ok(Math.abs(m.h/baseline[i].h-2.4)<1e-9);
   assert.equal(m.colour,baseline[i].colour);assert.equal(m.alpha,baseline[i].alpha);
   assert.ok(Math.abs(m.x+m.w/2-baseline[i].x-baseline[i].w/2)<1e-9,'Scaling keeps timing positions fixed');
  });
  const otherPaint=await page.evaluate(()=>({arrow:window.__meterArrow,background:window.__meterBackground}));
  assert.equal(await page.locator('#hud-opacity-label').textContent(),'判定条不透明度');
  const theme=await page.evaluate(()=>({accent:getComputedStyle(document.getElementById('hudLayoutPanel')).getPropertyValue('--edit-accent').trim(),button:getComputedStyle(document.getElementById('resetHudPart')).backgroundColor,outline:getComputedStyle(document.querySelector('.hud-edit-box.selected')).borderTopColor}));
  assert.deepEqual(theme,{accent:'#adedd2',button:'rgb(32, 43, 42)',outline:'rgb(173, 237, 210)'},'Layout editor uses the player mint and charcoal theme');
  await page.locator('#hud-opacity').evaluate(el=>{el.value='25';el.dispatchEvent(new Event('input',{bubbles:true}));});
  const faintPlate=await page.evaluate(ms=>window.__meterDraw(ms),time);
  assert.deepEqual(faintPlate,resized,'Plate opacity does not change any marker');
  const faintOther=await page.evaluate(()=>({arrow:window.__meterArrow,background:window.__meterBackground}));
  assert.equal(faintOther.arrow[0].alpha,otherPaint.arrow[0].alpha*.25);
  faintOther.background.forEach((p,i)=>{if(p.y>=1052&&p.y<=1054)assert.equal(p.alpha,otherPaint.background[i].alpha*.25);});
  await page.locator('#hud-opacity').evaluate(el=>{el.value='0';el.dispatchEvent(new Event('input',{bubbles:true}));});
  assert.deepEqual(await page.evaluate(ms=>window.__meterDraw(ms),time),resized,'Markers remain visible with a fully transparent plate');
  assert.equal(await page.evaluate(()=>window.__meterArrow[0].alpha),0);
  await page.locator('#hudPart').selectOption('combo');await page.locator('#hudPart').selectOption('error');
  assert.equal(await page.locator('#hud-opacity').inputValue(),'0','Zero opacity survives changing components');
  await page.locator('#hud-opacity').evaluate(el=>{el.value='100';el.dispatchEvent(new Event('input',{bubbles:true}));});
  await page.locator('#hud-beam-opacity').evaluate(el=>{el.value='35';el.dispatchEvent(new Event('input',{bubbles:true}));});
  assert.equal(await page.locator('#hud-beam-opacity-value').textContent(),'35%');
  const dimmed=await page.evaluate(ms=>window.__meterDraw(ms),time);
  dimmed.forEach((m,i)=>{assert.ok(Math.abs(m.alpha-resized[i].alpha*.35)<1e-9);assert.equal(m.colour,resized[i].colour);assert.equal(m.w,resized[i].w);});
  assert.deepEqual(await page.evaluate(()=>({arrow:window.__meterArrow,background:window.__meterBackground})),otherPaint,'Marker opacity leaves the meter and triangle unchanged');
  await page.locator('#hud-beam-opacity').evaluate(el=>{el.value='0';el.dispatchEvent(new Event('input',{bubbles:true}));});
  assert.ok((await page.evaluate(ms=>window.__meterDraw(ms),time)).every(m=>m.alpha===0),'Zero opacity hides all markers');
  await page.locator('#hud-beam-opacity').evaluate(el=>{el.value='35';el.dispatchEvent(new Event('input',{bubbles:true}));});
  await page.screenshot({path:path.join(output,'editor.png')});
  await page.locator('#hudPart').selectOption('combo');assert.equal(await page.locator('#hud-beam-control').isVisible(),false);
  assert.equal(await page.locator('#hud-beam-opacity-control').isVisible(),false);
  await page.locator('#closeHudEdit').click();
  await page.keyboard.press('Escape');await page.waitForTimeout(400);
  await page.evaluate(ms=>window.__mania.drawFrame(ms),time);
  await page.screenshot({path:path.join(output,'playback.png')});
  await page.reload();await page.waitForFunction(()=>window.__mania?.skinState().loadedKey);
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('mania-hud-layout-v1')).error.beamScale),2.4);
  assert.equal(await page.evaluate(()=>window.__mania.layoutState().error.beamScale),2.4);
  assert.equal(await page.evaluate(()=>window.__mania.layoutState().error.beamOpacity),.35);
  await page.locator('#bidInput').fill('4565844');
  await page.locator('#fOsr').setInputFiles(replayPath);await page.locator('#btnLoad').click();
  await page.locator('#sourceScene').waitFor({state:'hidden',timeout:120000});
  await page.evaluate(()=>document.getElementById('btnEditHud').click());
  await page.locator('#hudPart').selectOption('error');assert.equal(await page.locator('#hud-beam-scale').inputValue(),'2.4');
  assert.equal(await page.locator('#hud-beam-opacity').inputValue(),'35');
  await page.locator('#resetHudPart').click();assert.equal(await page.locator('#hud-beam-scale').inputValue(),'1');
  assert.equal(await page.locator('#hud-beam-opacity').inputValue(),'100');
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(output,'results.json'),JSON.stringify({markers:resized,averageRange:[Math.min(...averages),Math.max(...averages)]},null,2));
  console.log('PASS: real OSR markers, inverted eased arrow, independent plate/beam opacity including zero, mint editor, resizing and persistence/reset, no browser errors');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
